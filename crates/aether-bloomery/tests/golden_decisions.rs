//! Pinned wire bytes for a representative [`Decisions`] value (ADR-0187 / #4944).
//!
//! The journal's decisions column is a persisted surface. A shape change in the
//! reachable graph — adding a field to [`StageProgress`], reordering a
//! [`Decision`] variant — must fail this fixture rather than wait for the next
//! boot replay to abort.
//!
//! Coverage is the whole of the fixture's value: a family the representative
//! omits is a family whose payload type can gain a field, encode wider on every
//! new row, and still pass here — while boot replay of the rows written before
//! it fatally aborts. So every effect family carrying a payload type of its own
//! appears below, and each payload's `Option` fields are populated rather than
//! left `None`, since a `None` encodes its tag and nothing of the shape behind
//! it.

use aether_bloomery::{
    AgentProfile, BloomId, CandidateRef, ClaimRefKind, ConfigRegistry, Decision, Decisions, Digest, Evidence,
    EvidenceKind, ExecutionLimits, Harness, LandingReceipt, NetworkProfile, OrphanClaimRelease,
    OrphanClaimReleaseCompletion, Outcome, ProjectedReceipt, ReasoningEffort, ResolutionClaim, ResolvedBloom,
    ResolvedModel, StageCatalog, StageId, StageProgress, ToolPolicy, Transformation, VerifyFailureSet, VerifyProof,
    Wedge, WorkpieceId,
};
use aether_data::wire::{from_bytes, to_vec};

fn digest(seed: u8) -> Digest {
    Digest::from_bytes([seed; 32])
}

fn configs() -> ConfigRegistry {
    let mut registry = ConfigRegistry::default();
    registry.insert_named("aether.bloomery.model_override", digest(17));
    registry
}

// The two effects whose payloads are deep enough to read as values of their
// own: a dispatch carries a whole `Transformation`, an `AgentProfile`, and a
// `ConfigRegistry`; a resolution carries a `ResolvedBloom` with a claim under
// it. Lifted out so `representative` stays a readable list of families.
fn dispatch_attempt(bloom: BloomId, workpiece: WorkpieceId) -> Decision {
    Decision::DispatchAttempt {
        bloom,
        workpiece,
        stage: StageId::Verify,
        transformation: Transformation {
            command: "verify.check".into(),
            inputs: vec![digest(12)],
            checkout: digest(13),
            diff_base: Some(digest(14)),
            outputs: vec!["verdict".into()],
            image: "iama/verify:1".into(),
            limits: ExecutionLimits { wall_clock_secs: 900 },
            network: NetworkProfile::Restricted,
            description: Some("verify the candidate".into()),
            model: Some(ResolvedModel {
                harness: Harness::Claude,
                model: "claude-opus-4-8".into(),
                effort: ReasoningEffort::High,
            }),
        },
        scope_revision: digest(15),
        candidate: Some(digest(16)),
        profile: AgentProfile {
            harness: Harness::Codex,
            model: "gpt-5-codex".into(),
            effort: ReasoningEffort::Max,
            tools: ToolPolicy::Allow(vec!["read".into()]),
        },
        configs: configs(),
    }
}

fn set_resolved(bloom: BloomId, workpiece: WorkpieceId) -> Decision {
    Decision::SetResolved {
        bloom,
        resolved: ResolvedBloom {
            bloom,
            tree: digest(18),
            head: digest(19),
            lineage: vec![digest(20)],
            resolution_claims: vec![ResolutionClaim {
                workpiece,
                scope_revision: digest(15),
                candidate: digest(16),
                evidence: Evidence { subject: digest(16), kind: EvidenceKind::ResolutionClaim, detail: digest(21) },
            }],
        },
    }
}

