// Repinned again for the manager override (#4957): `Decision::RecordAdjudication`
// and `Decision::RecordOperatorRepair` append past it, carrying the `Adjudication`
// / `Disposition` / `OperatorRepair` payloads — the two rows an operator's own
// decision writes. Every prior byte is unchanged except the effect count, which
// this appends two to; the whole delta is the tail.
