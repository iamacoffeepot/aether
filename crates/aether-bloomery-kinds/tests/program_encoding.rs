#[test]
fn the_canonical_encoding_of_each_request_source_is_pinned() -> Result<(), Box<dyn Error>> {
    // Tripwire: the canonical encoding of a request record and its two
    // source variants, and the digest each would take as an artifact. Pins
    // the request record and both source variants; drift re-identifies
    // every recorded request and breaks the `(cause, source)` dedup key
    // across a restart.
    let pins = fixture_pins();
    let reaction = Requested {
        program: pins.program.clone(),
        input: pins.input,
        source: RequestSource::Reaction {
            bundle: Digest::from_bytes([4; 32]),
            reactor: ReactorName::new("example.reactor").expect("valid name"),
            rule: RuleName::new("on_event").expect("valid name"),
            ordinal: 1,
        },
    };
    let payload = Requested::encode_storage(&StorageData::from_value(reaction))?;
    let digest = artifact_digest(Requested::ID, &payload);
    assert_eq!(payload, TRIPWIRE_REQUESTED_REACTION_PAYLOAD, "payload={payload:?}");
    assert_eq!(digest.as_bytes(), &TRIPWIRE_REQUESTED_REACTION_DIGEST, "digest={digest}");

    let native = Requested {
        program: pins.program,
        input: pins.input,
        source: RequestSource::Native { origin: NativeOrigin::new("example.origin").expect("valid name"), key: 7 },
    };
    let payload = Requested::encode_storage(&StorageData::from_value(native))?;
    let digest = artifact_digest(Requested::ID, &payload);
    assert_eq!(payload, TRIPWIRE_REQUESTED_NATIVE_PAYLOAD, "payload={payload:?}");
    assert_eq!(digest.as_bytes(), &TRIPWIRE_REQUESTED_NATIVE_DIGEST, "digest={digest}");
    Ok(())
}

