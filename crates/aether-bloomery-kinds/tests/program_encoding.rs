//! Canonical encoding of one fixed program declaration.

use std::error::Error;

use aether_bloomery_kinds::{
    Digest, ExecutorName, Fault, FaultReason, Mode, OpaqueBytes, Program, ProgramName, Ref, Transition, Utf8Text,
    artifact_digest,
};
use aether_data::{Kind, Storage, StorageData};

fn fixture_program() -> Program {
    Program {
        name: ProgramName::new("example.program").expect("valid name"),
        input: OpaqueBytes::ID,
        result: Utf8Text::ID,
        mode: Mode::Pure,
        intent: "one sentence of meaning for a planner".into(),
    }
}

#[test]
fn the_canonical_encoding_of_one_fixed_program_is_pinned() -> Result<(), Box<dyn Error>> {
    // Tripwire: the canonical encoding of a program declaration and the digest
    // every stored program in every journal depends on. Catches drift in field
    // tags, KindId leaves, Mode variants, or the framing, which would silently
    // re-identify every program.
    let payload = Program::encode_storage(&StorageData::from_value(fixture_program()))?;
    let digest = artifact_digest(Program::ID, &payload);
    assert_eq!(payload, TRIPWIRE_PROGRAM_PAYLOAD, "payload={payload:?}");
    assert_eq!(digest.as_bytes(), &TRIPWIRE_PROGRAM_DIGEST, "digest={digest}");
    Ok(())
}

