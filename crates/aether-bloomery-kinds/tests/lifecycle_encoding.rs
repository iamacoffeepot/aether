//! Canonical encoding of the reactor-bundle lifecycle records, and the
//! zero-`live_from` refusal on both construction and decode.

use std::error::Error;

use aether_bloomery_kinds::{
    Activated, ActivationRejected, Detail, Digest, Head, LiveFromError, OpaqueBytes, ReactionFailed, ReactorName, Seq,
    artifact_digest,
};
use aether_data::{Kind, Storage, StorageData, StorageError};

fn fixture_head() -> Head<OpaqueBytes> {
    Head::new("example.cluster")
}

#[test]
fn the_canonical_encoding_of_each_lifecycle_record_is_pinned() -> Result<(), Box<dyn Error>> {
    // Tripwire: the canonical encoding of each driver-written lifecycle
    // record, and the digest each would take as an artifact. Catches drift
    // in field tags, Head/Digest/Detail leaves, or the LiveFrom newtype,
    // which would silently re-identify every recorded activation or
    // reaction failure.
    let activated = Activated::new(fixture_head(), Digest::from_bytes([5; 32]), Seq(3)).expect("nonzero live_from");
    let payload = Activated::encode_storage(&StorageData::from_value(activated))?;
    let digest = artifact_digest(Activated::ID, &payload);
    assert_eq!(payload, TRIPWIRE_ACTIVATED_PAYLOAD, "payload={payload:?}");
    assert_eq!(digest.as_bytes(), &TRIPWIRE_ACTIVATED_DIGEST, "digest={digest}");

    let rejected =
        ActivationRejected { head: fixture_head(), bundle: Digest::from_bytes([5; 32]), reason: Detail::new("no") };
    let payload = ActivationRejected::encode_storage(&StorageData::from_value(rejected))?;
    let digest = artifact_digest(ActivationRejected::ID, &payload);
    assert_eq!(payload, TRIPWIRE_ACTIVATION_REJECTED_PAYLOAD, "payload={payload:?}");
    assert_eq!(digest.as_bytes(), &TRIPWIRE_ACTIVATION_REJECTED_DIGEST, "digest={digest}");

    let failed = ReactionFailed {
        bundle: Digest::from_bytes([5; 32]),
        reactor: Some(ReactorName::new("example.reactor").expect("valid name")),
        reason: Detail::new("no"),
    };
    let payload = ReactionFailed::encode_storage(&StorageData::from_value(failed))?;
    let digest = artifact_digest(ReactionFailed::ID, &payload);
    assert_eq!(payload, TRIPWIRE_REACTION_FAILED_PAYLOAD, "payload={payload:?}");
    assert_eq!(digest.as_bytes(), &TRIPWIRE_REACTION_FAILED_DIGEST, "digest={digest}");
    Ok(())
}

#[test]
fn activated_refuses_a_zero_live_from_on_construction_and_decode() -> Result<(), Box<dyn Error>> {
    // Catches a decode path that skips the LiveFrom check. The twin puts a
    // raw u64 in the same field position as the private LiveFrom newtype.
    #[derive(Debug, Clone, PartialEq, Eq, aether_data::Storage)]
    #[kind(name = "bloomery.activated")]
    struct Twin {
        head: Head<OpaqueBytes>,
        bundle: Digest,
        live_from: u64,
    }

    assert_eq!(Activated::new(fixture_head(), Digest::from_bytes([5; 32]), Seq(0)), Err(LiveFromError::Zero));

    let bytes = Twin::encode_storage(&StorageData::from_value(Twin {
        head: fixture_head(),
        bundle: Digest::from_bytes([5; 32]),
        live_from: 0,
    }))?;
    match Activated::decode_storage(&bytes) {
        Err(StorageError::Invariant { kind: "LiveFrom", reason: "zero" }) => Ok(()),
        other => panic!("expected LiveFrom zero invariant, got {other:?}"),
    }
}

